using System.Globalization;
using System.Net;
using System.Text;
using POS.Shared.Models;

namespace POS.Client.Services;

/// <summary>Formats a saved, supervisor-authorized Z snapshot; never queries sales or changes counters.</summary>
public static class ZReadingHtmlFormatter
{
    public static string Format(ZReadingReportDto report, bool isReprint = false)
    {
        ArgumentNullException.ThrowIfNull(report);
        var h = new StringBuilder("""
            <!doctype html><html lang="en"><head><meta charset="utf-8">
            <meta name="viewport" content="width=device-width,initial-scale=1">
            <meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'; base-uri 'none'; form-action 'none'">
            <title>Z-Reading report</title><style>
            @page { size: 80mm 200mm; margin: 0; }
            * { box-sizing: border-box; } body { max-width:80mm; margin:0 auto; padding:3mm; font:10.5px/1.3 Consolas,'Courier New',monospace; color:#000; background:#fff; overflow-wrap:anywhere; }
            h1 {font-size:14px;margin:0;text-align:center;} h2 {font-size:12px;margin:3mm 0 1mm;border-top:1px dashed #000;padding-top:1.5mm;} p {margin: .6mm 0;} .center {text-align:center;} .row {display:flex;justify-content:space-between;gap:2mm;margin:.5mm 0;} .row span:last-child {text-align:right;font-variant-numeric:tabular-nums;} .total {font-weight:bold;font-size:12px;} table {width:100%;border-collapse:collapse;table-layout:fixed;} th,td {padding:1mm .5mm;text-align:left;vertical-align:top;} th {border-bottom:1px dashed #000;} td:not(:first-child),th:not(:first-child) {text-align:right;} td:first-child,th:first-child {width:48%;} .note {font-size:9px;} .copy {font-weight:bold;text-align:center;border:1px dashed #000;padding:1mm;} tr {break-inside:avoid;} button {display:none;}
            </style></head><body>
            """);
        h.Append("<h1>").Append(E(report.BusinessName ?? report.BranchName)).Append("</h1>");
        Line("Branch: " + report.BranchName); Line("Outlet: " + report.OutletName);
        if (!string.IsNullOrWhiteSpace(report.Address)) Line(report.Address);
        Line("TIN: " + (report.Tin ?? "Not configured — verify registration"));
        Line("Terminal: " + report.TerminalCode + " / " + report.TerminalName);
        Line("MIN: " + (report.MachineIdentificationNumber ?? "Not configured"));
        Line("S/N: " + (report.SerialNumber ?? "Not configured"));
        Line("PTU: " + (report.PermitToUseNumber ?? "Not configured"));
        h.Append("<h2 class=\"center\">Z-READING REPORT</h2>");
        if (isReprint) h.Append("<p class=\"copy\">REPRINT — SAME FINALIZED REPORT</p>");
        Line($"Business date: {report.BusinessDate:yyyy-MM-dd}");
        Line("Period start: " + Stamp(report.PeriodStartUtc));
        Line("Period end (exclusive): " + Stamp(report.PeriodEndUtc));
        Line("Generated: " + Stamp(report.GeneratedAt)); Line("Generated by: " + report.GeneratedBy);
        Line("Report ID: " + report.Id);
        Row("Beginning invoice", report.FirstInvoiceNumber ?? "N/A");
        Row("Ending invoice", report.LastInvoiceNumber ?? "N/A");
        Row("Beginning refund ID", report.FirstRefundId?.ToString(CultureInfo.InvariantCulture) ?? "N/A");
        Row("Ending refund ID", report.LastRefundId?.ToString(CultureInfo.InvariantCulture) ?? "N/A");
        Line("Refund IDs are internal record references; no separate registered refund-number series exists in this system.");
        foreach (var kind in new[] { "RETURN", "VOID" })
        {
            var events = report.Adjustments.Where(x => x.Kind == kind).OrderBy(x => x.EventAtUtc).ThenBy(x => x.EventId).ToList();
            Row("Beginning " + kind + " ID", events.FirstOrDefault()?.EventId.ToString(CultureInfo.InvariantCulture) ?? "N/A");
            Row("Ending " + kind + " ID", events.LastOrDefault()?.EventId.ToString(CultureInfo.InvariantCulture) ?? "N/A");
        }
        Row("Reset counter", report.ResetCounter?.ToString(CultureInfo.InvariantCulture) ?? "Not configured");
        Row("Internal Z number", report.ZNumber?.ToString(CultureInfo.InvariantCulture) ?? "Not configured");
        Heading("Accumulated gross sales");
        Row("Previous accumulated", Money(report.PreviousAccumulatedSales));
        Row("Present accumulated", Money(report.PresentAccumulatedSales));
        Row("Gross sales for day", Money(report.GrossSales));
        Heading("Sales summary");
        Row("Invoices / Returns / Voids", $"{report.SaleCount} / {report.ReturnCount} / {report.VoidCount}");
        Row("Gross sales", Money(report.GrossSales)); Row("Less discounts", Money(-report.Discounts));
        Row("Less VAT removal / residual", Money(-report.VatAdjustment));
        Row("Less returns", Money(-report.Returns)); Row("Less void adjustments", Money(-report.Voids));
        Row("NET SALES", Money(report.NetSales), true);
        Products("Product sales — gross line value", report.Products, false);
        Products("Product returns — refund value", report.ReturnProducts, true);
        Products("Product voids — historical gross lines", report.VoidProducts, true);
        Products("VAT-exempt product detail (subset)", report.ExemptProducts, false);
        Heading("Tax totals");
        Row("VATable sales", Money(report.VatableSales)); Row("VAT amount", Money(report.VatAmount));
        Row("VAT-exempt sales", Money(report.VatExemptSales)); Row("Zero-rated sales", Money(report.ZeroRatedSales));
        Row("Original tax/sales breakdown total", Money(report.VatableSales + report.VatAmount + report.VatExemptSales + report.ZeroRatedSales));
        Row("VAT on returns", Money(-report.ReturnVatAmount)); Row("VAT on voids", Money(-report.VoidVatAmount));
        Row("Net VAT (see precision warning)", Money(report.NetVatAmount));
        Heading("Payment method summary");
        Line("Payment entries: split tenders count separately, not item quantities.");
        foreach (var p in report.Payments)
        {
            Line(p.PaymentMethod); Row($"Collections ({p.PaymentCount})", Money(p.Collections));
            Row($"Refund entries ({p.RefundCount})", Money(-p.Refunds)); Row("Net collections", Money(p.NetCollections));
        }
        Row("TOTAL NET COLLECTIONS", Money(report.Payments.Sum(x => x.NetCollections)), true);
        Heading("Discount totals");
        foreach (var d in report.DiscountTotals) Row($"{d.DiscountCode} / {d.DiscountName} ({d.Count})", Money(d.Amount));
        Row("Total discounts", Money(report.Discounts));
        Heading("Cashier sales and adjustment summary");
        foreach (var c in report.Cashiers)
        {
            Line("Cashier: " + c.CashierName); Row("Sales / return / void count", $"{c.SaleCount} / {c.ReturnCount} / {c.VoidCount}");
            Row("Sold / returned / voided item qty", $"{Qty(c.ItemQuantity)} / {Qty(c.ReturnQuantity)} / {Qty(c.VoidQuantity)}");
            Row("Gross sales", Money(c.GrossSales)); Row("Discounts", Money(-c.Discounts));
            Row("Returns", Money(-c.Returns)); Row("Voids", Money(-c.Voids)); Row("Cashier net", Money(c.NetSales), true);
        }
        Row("TOTAL CASHIER NET", Money(report.Cashiers.Sum(x => x.NetSales)), true);
        Line("Sales belong to sale cashier; returns/voids to processing cashier.");
        Heading("Cash drawer by shift");
        Line("Opening floats are separate drawers/handoffs, not added to sales or assumed one daily opening fund.");
        foreach (var s in report.Shifts)
        {
            Line($"Shift #{s.ShiftId} / Cashier {s.CashierId}"); Line(Stamp(s.OpenedAt) + " to " + (s.ClosedAt.HasValue ? Stamp(s.ClosedAt.Value) : "OPEN"));
            Row("Opening float", Money(s.OpeningFloat)); Row("Cash sales", Money(s.CashSales));
            Row("Cash refunds", Money(-s.CashRefunds)); Row("Cash in", Money(s.CashIn));
            Row("Cash out / petty cash", Money(-s.CashOut)); Row("Cash drops", Money(-s.CashDrops));
            Row("Expected drawer", Money(s.ExpectedBalance)); Row("Counted drawer", s.ActualCountedBalance.HasValue ? Money(s.ActualCountedBalance.Value) : "Not recorded");
            Row("Short / Over", s.Discrepancy.HasValue ? Money(s.Discrepancy.Value) : "Not recorded");
        }
        Heading("Adjustment audit");
        foreach (var a in report.Adjustments) Line($"{a.Kind} #{a.EventId} / Invoice {a.OriginalInvoiceNumber ?? "N/A"} / {a.ProcessedBy} / {Stamp(a.EventAtUtc)} / {Money(-a.Amount)}");
        Heading("Report notes");
        foreach (var warning in report.Warnings) Line(warning);
        Line("FINALIZED SNAPSHOT — NOT A SALES INVOICE. Internal numbering does not establish BIR accreditation. Reset and cumulative configuration require operator/RDO review.");
        h.Append("</body></html>");
        return h.ToString();

        void Line(string text) => h.Append("<p>").Append(E(text)).Append("</p>");
        void Heading(string text) => h.Append("<h2>").Append(E(text)).Append("</h2>");
        void Row(string label, string value, bool total = false) => h.Append(total ? "<div class=\"row total\"><span>" : "<div class=\"row\"><span>").Append(E(label)).Append("</span><span>").Append(E(value)).Append("</span></div>");
        void Products(string title, List<ZReadingProductDto> products, bool negative)
        {
            Heading(title);
            if (products.Count == 0) { Line("None"); return; }
            h.Append("<table><thead><tr><th>Product</th><th>Qty</th><th>Value</th></tr></thead><tbody>");
            foreach (var p in products) h.Append("<tr><td>").Append(E(p.ProductName)).Append("</td><td>").Append(Qty(p.Quantity)).Append("</td><td>").Append(Money(negative ? -p.Value : p.Value)).Append("</td></tr>");
            h.Append("</tbody></table>");
        }
    }
    private static string E(string? value) => WebUtility.HtmlEncode(value ?? "");
    private static string Qty(decimal value) => value.ToString("0.###", CultureInfo.InvariantCulture);
    private static string Money(decimal value) => (value < 0 ? "-PHP " : "PHP ") + Math.Abs(value).ToString("N2", CultureInfo.InvariantCulture);
    private static string Stamp(DateTime utc) => DateTime.SpecifyKind(utc, DateTimeKind.Utc).AddHours(8).ToString("yyyy-MM-dd HH:mm", CultureInfo.InvariantCulture) + " Asia/Manila";
}
