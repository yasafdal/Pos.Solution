-- Seed FNB Modifier Groups and Options into pos_db
BEGIN;
SET LOCAL lock_timeout = '10s';

DO $$
BEGIN
    IF current_database() <> 'pos_db' THEN
        RAISE EXCEPTION 'SeedProductModifiers.sql must run against pos_db';
    END IF;
END $$;

-- Ensure tables exist
CREATE TABLE IF NOT EXISTS "ModifierGroup" (
    modifier_group_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL,
    is_required boolean NOT NULL DEFAULT false,
    min_selections integer NOT NULL DEFAULT 0,
    max_selections integer NOT NULL DEFAULT 1,
    display_order integer NOT NULL DEFAULT 0,
    is_active boolean NOT NULL DEFAULT true,
    CONSTRAINT "CK_ModifierGroup_name" CHECK (length(btrim(name)) > 0),
    CONSTRAINT "CK_ModifierGroup_min_max" CHECK (min_selections >= 0 AND max_selections >= min_selections)
);

CREATE TABLE IF NOT EXISTS "ModifierOption" (
    modifier_option_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    modifier_group_id integer NOT NULL,
    name varchar(100) NOT NULL,
    price numeric(18,2) NOT NULL DEFAULT 0.00,
    display_order integer NOT NULL DEFAULT 0,
    is_active boolean NOT NULL DEFAULT true,
    CONSTRAINT "FK_ModifierOption_ModifierGroup" FOREIGN KEY (modifier_group_id) REFERENCES "ModifierGroup"(modifier_group_id) ON DELETE CASCADE,
    CONSTRAINT "CK_ModifierOption_name" CHECK (length(btrim(name)) > 0),
    CONSTRAINT "CK_ModifierOption_price" CHECK (price >= 0)
);
CREATE INDEX IF NOT EXISTS "IX_ModifierOption_modifier_group_id" ON "ModifierOption" (modifier_group_id);

-- Seed Modifier Groups
INSERT INTO "ModifierGroup" ("modifier_group_id", "name", "is_required", "min_selections", "max_selections", "display_order", "is_active")
OVERRIDING SYSTEM VALUE VALUES
(1, 'Size', true, 1, 1, 1, true),
(2, 'Sugar Level', true, 1, 1, 2, true),
(3, 'Add-ons & Extras', false, 0, 3, 3, true)
ON CONFLICT ("modifier_group_id") DO UPDATE 
SET "name" = EXCLUDED."name", 
    "is_required" = EXCLUDED."is_required", 
    "min_selections" = EXCLUDED."min_selections", 
    "max_selections" = EXCLUDED."max_selections",
    "display_order" = EXCLUDED."display_order",
    "is_active" = EXCLUDED."is_active";

SELECT setval(pg_get_serial_sequence('"ModifierGroup"', 'modifier_group_id'), coalesce(max("modifier_group_id"), 1), true) FROM "ModifierGroup";

-- Seed Modifier Options
INSERT INTO "ModifierOption" ("modifier_option_id", "modifier_group_id", "name", "price", "display_order", "is_active")
OVERRIDING SYSTEM VALUE VALUES
-- Group 1: Size
(101, 1, 'Regular', 0.00, 1, true),
(102, 1, 'Large', 30.00, 2, true),
-- Group 2: Sugar Level
(201, 2, '0% (No Sugar)', 0.00, 1, true),
(202, 2, '50% (Half Sugar)', 0.00, 2, true),
(203, 2, '100% (Regular)', 0.00, 3, true),
-- Group 3: Add-ons & Extras
(301, 3, 'Extra Shot', 40.00, 1, true),
(302, 3, 'Pearls / Sinkers', 20.00, 2, true),
(303, 3, 'Caramel Syrup', 25.00, 3, true)
ON CONFLICT ("modifier_option_id") DO UPDATE 
SET "modifier_group_id" = EXCLUDED."modifier_group_id",
    "name" = EXCLUDED."name",
    "price" = EXCLUDED."price",
    "display_order" = EXCLUDED."display_order",
    "is_active" = EXCLUDED."is_active";

SELECT setval(pg_get_serial_sequence('"ModifierOption"', 'modifier_option_id'), coalesce(max("modifier_option_id"), 1), true) FROM "ModifierOption";

COMMIT;
