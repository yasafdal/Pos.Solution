-- Idempotent PostgreSQL script for Sequence Management (Order and Invoice Sequences)
-- Run manually against pos_db; never invoked at application startup.
BEGIN;
SET LOCAL lock_timeout = '10s';

DO $$
BEGIN
    IF current_database() <> 'pos_db' THEN
        RAISE EXCEPTION 'SequenceManagement.sql must run against pos_db';
    END IF;
END $$;

-- 1. OrderSequences table
CREATE TABLE IF NOT EXISTS "OrderSequences" (
    order_sequence_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    outlet_id INT NOT NULL UNIQUE,
    last_issued_number BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "FK_OrderSequences_Outlet" FOREIGN KEY (outlet_id) REFERENCES "Outlets"("OutletId") ON DELETE CASCADE
);

-- 2. InvoiceSequences table
CREATE TABLE IF NOT EXISTS "InvoiceSequences" (
    invoice_sequence_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    outlet_id INT NOT NULL,
    series_code VARCHAR(50) NOT NULL,
    prefix VARCHAR(20) NULL,
    starting_number BIGINT NOT NULL DEFAULT 1,
    ending_number BIGINT NULL,
    last_issued_number BIGINT NOT NULL DEFAULT 0,
    padding_length INT NOT NULL DEFAULT 7,
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "FK_InvoiceSequences_Outlet" FOREIGN KEY (outlet_id) REFERENCES "Outlets"("OutletId") ON DELETE CASCADE,
    CONSTRAINT "CK_InvoiceSequences_numbers" CHECK (starting_number >= 0 AND (ending_number IS NULL OR ending_number >= starting_number))
);

CREATE INDEX IF NOT EXISTS "IX_InvoiceSequences_outlet_id" ON "InvoiceSequences" (outlet_id);

-- 3. Add columns to Orders table if not already present
ALTER TABLE "Orders" ADD COLUMN IF NOT EXISTS invoice_sequence_id INT NULL;
ALTER TABLE "Orders" ADD COLUMN IF NOT EXISTS "InvoiceNumber" VARCHAR(50) NULL;
ALTER TABLE "Orders" ADD COLUMN IF NOT EXISTS invoice_issued_at TIMESTAMP WITHOUT TIME ZONE NULL;

-- Unique index on InvoiceNumber where not null
CREATE UNIQUE INDEX IF NOT EXISTS "IX_Orders_InvoiceNumber" ON "Orders" ("InvoiceNumber") WHERE "InvoiceNumber" IS NOT NULL;

COMMIT;
