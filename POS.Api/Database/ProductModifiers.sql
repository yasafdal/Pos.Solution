-- Run manually against pos_db; never invoked at application startup.
-- Uses the current schema (public for the application; isolated schema in tests).
-- Creates tables for Product Modifiers (Modifier Groups, Modifier Options, and Product Modifier Group associations).
BEGIN;
SET LOCAL lock_timeout = '10s';
DO $$
BEGIN
    IF current_database() <> 'pos_db' THEN
        RAISE EXCEPTION 'ProductModifiers.sql must run against pos_db';
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS "ModifierGroup" (
    modifier_group_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL,
    is_required boolean NOT NULL DEFAULT false,
    min_selections integer NOT NULL DEFAULT 0,
    max_selections integer NOT NULL DEFAULT 1,
    display_order integer NOT NULL DEFAULT 0,
    is_active boolean NOT NULL DEFAULT true,
    CONSTRAINT "CK_ModifierGroup_name" CHECK (length(btrim(name)) > 0),
    CONSTRAINT "CK_ModifierGroup_min_max" CHECK (min_selections >= 0 AND max_selections >= min_selections)
);

CREATE TABLE IF NOT EXISTS "ModifierOption" (
    modifier_option_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    modifier_group_id integer NOT NULL,
    name varchar(100) NOT NULL,
    price numeric(18,2) NOT NULL DEFAULT 0.00,
    display_order integer NOT NULL DEFAULT 0,
    is_active boolean NOT NULL DEFAULT true,
    CONSTRAINT "FK_ModifierOption_ModifierGroup" FOREIGN KEY (modifier_group_id) REFERENCES "ModifierGroup"(modifier_group_id) ON DELETE CASCADE,
    CONSTRAINT "CK_ModifierOption_name" CHECK (length(btrim(name)) > 0),
    CONSTRAINT "CK_ModifierOption_price" CHECK (price >= 0)
);
CREATE INDEX IF NOT EXISTS "IX_ModifierOption_modifier_group_id" ON "ModifierOption" (modifier_group_id);

CREATE TABLE IF NOT EXISTS "ProductModifierGroup" (
    product_modifier_group_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id integer NOT NULL,
    modifier_group_id integer NOT NULL,
    display_order integer NOT NULL DEFAULT 0,
    CONSTRAINT "FK_ProductModifierGroup_Product" FOREIGN KEY (product_id) REFERENCES "Products"("ProductId") ON DELETE CASCADE,
    CONSTRAINT "FK_ProductModifierGroup_ModifierGroup" FOREIGN KEY (modifier_group_id) REFERENCES "ModifierGroup"(modifier_group_id) ON DELETE CASCADE,
    CONSTRAINT "UQ_Product_ModifierGroup" UNIQUE (product_id, modifier_group_id)
);
CREATE INDEX IF NOT EXISTS "IX_ProductModifierGroup_product_id" ON "ProductModifierGroup" (product_id);
CREATE INDEX IF NOT EXISTS "IX_ProductModifierGroup_modifier_group_id" ON "ProductModifierGroup" (modifier_group_id);

COMMIT;
