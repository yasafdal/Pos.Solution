-- Run manually against pos_db; never invoked at application startup.
-- Uses the current schema (public for the application; isolated schema in tests).
-- Existing branches remain unassigned. Re-running preserves edited descriptions.
BEGIN;
SET LOCAL lock_timeout = '10s';
DO $$
BEGIN
    IF current_database() <> 'pos_db' THEN
        RAISE EXCEPTION 'BusinessTypes.sql must run against pos_db';
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS "BusinessType" (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type varchar(50) NOT NULL,
    description varchar(250) NOT NULL,
    CONSTRAINT "CK_BusinessType_type" CHECK (length(btrim(type)) > 0 AND type = upper(btrim(type))),
    CONSTRAINT "CK_BusinessType_description" CHECK (length(btrim(description)) > 0)
);
CREATE UNIQUE INDEX IF NOT EXISTS "UX_BusinessType_type" ON "BusinessType" (type);

INSERT INTO "BusinessType" (type, description) VALUES
    ('RETAIL', 'Product-based sales'),
    ('FNB', 'Food & Beverage'),
    ('SERVICE', 'Service-based transactions'),
    ('HYBRID', 'Combination of retail and F&B or services')
ON CONFLICT (type) DO NOTHING;

ALTER TABLE "Branches" ADD COLUMN IF NOT EXISTS "BusinessTypeId" integer NULL;
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
        WHERE conname = 'FK_Branches_BusinessType' AND conrelid = '"Branches"'::regclass) THEN
        ALTER TABLE "Branches" ADD CONSTRAINT "FK_Branches_BusinessType"
            FOREIGN KEY ("BusinessTypeId") REFERENCES "BusinessType" (id) ON DELETE RESTRICT;
    END IF;
END $$;
CREATE INDEX IF NOT EXISTS "IX_Branches_BusinessTypeId" ON "Branches" ("BusinessTypeId");
COMMIT;
