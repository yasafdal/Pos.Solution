-- Canonicalize identifiers only after checking duplicates. Existing PTU/MIN/serial and numbering values are unchanged.
DO $identity$
BEGIN
    IF EXISTS (SELECT 1 FROM "Terminals" WHERE nullif(btrim("DeviceIdentifier"), '') IS NOT NULL
        GROUP BY lower(btrim("DeviceIdentifier")) HAVING count(*) > 1) THEN
        RAISE EXCEPTION 'Duplicate device identifiers. Resolve duplicates before migration; no terminal records were deleted.';
    END IF;
END $identity$;
CREATE FUNCTION pg_temp.canonical_terminal_identity(value text) RETURNS text LANGUAGE plpgsql AS $identity$
BEGIN
    IF nullif(btrim(value), '') IS NULL THEN RETURN NULL; END IF;
    BEGIN
        IF family(btrim(value)::inet) = 6 AND btrim(value)::inet <<= '::ffff:0:0/96'::inet THEN
            RETURN host('0.0.0.0'::inet + (btrim(value)::inet - '::ffff:0:0'::inet));
        END IF;
        RETURN host(btrim(value)::inet);
    EXCEPTION WHEN invalid_text_representation THEN RETURN lower(btrim(value)); END;
END $identity$;
DO $canonical_duplicates$
BEGIN
    IF EXISTS (SELECT 1 FROM "Terminals" WHERE pg_temp.canonical_terminal_identity("DeviceIdentifier") IS NOT NULL
        GROUP BY pg_temp.canonical_terminal_identity("DeviceIdentifier") HAVING count(*) > 1) THEN
        RAISE EXCEPTION 'Equivalent device IP addresses are assigned to multiple terminals. Resolve before migrating.';
    END IF;
END $canonical_duplicates$;
UPDATE "Terminals" SET "DeviceIdentifier" = pg_temp.canonical_terminal_identity("DeviceIdentifier");
UPDATE "Terminals" SET "IpAddress" = "DeviceIdentifier" WHERE pg_input_is_valid("DeviceIdentifier", 'inet');

DO $references$
DECLARE table_name text; column_name text; item record;
BEGIN
    FOREACH table_name IN ARRAY ARRAY['Orders','CashDrawerShifts','CashDrawerMovements','CashierSessions','CashierSwitchLogs','HeldSales','HeldSaleAuditLogs','ReceiptReprintLogs','SalesReturns','OrderSequences','InvoiceSequences']
    LOOP
        column_name := CASE WHEN table_name IN ('OrderSequences','InvoiceSequences') THEN 'outlet_id' ELSE 'OutletId' END;
        IF to_regclass(format('%I', table_name)) IS NULL THEN
            RAISE EXCEPTION 'Required legacy table % is missing. Complete the baseline schema before migrating.', table_name;
        END IF;
        EXECUTE format('ALTER TABLE %I RENAME COLUMN %I TO %I', table_name, column_name,
            CASE WHEN column_name = 'outlet_id' THEN 'terminal_id' ELSE 'TerminalId' END);
        FOR item IN SELECT conname FROM pg_constraint WHERE conrelid = to_regclass(format('%I', table_name)) AND conname LIKE '%Outlet%'
        LOOP
            EXECUTE format('ALTER TABLE %I RENAME CONSTRAINT %I TO %I', table_name, item.conname, replace(item.conname, 'Outlet', 'Terminal'));
        END LOOP;
        FOR item IN SELECT indexname FROM pg_indexes p WHERE p.schemaname = current_schema() AND p.tablename = table_name AND p.indexname LIKE '%Outlet%'
        LOOP
            EXECUTE format('ALTER INDEX %I RENAME TO %I', item.indexname, replace(item.indexname, 'Outlet', 'Terminal'));
        END LOOP;
    END LOOP;
END $references$;

DO $validate$
DECLARE history_table text; column_name text; invalid_count bigint;
BEGIN
    IF EXISTS (SELECT 1 FROM "Terminals" WHERE "OutletId" IS NULL) THEN
        RAISE EXCEPTION 'Not every terminal received an outlet. Migration rolled back.';
    END IF;
    FOREACH history_table IN ARRAY ARRAY['Orders','CashDrawerShifts','CashDrawerMovements','CashierSessions','CashierSwitchLogs','HeldSales','HeldSaleAuditLogs','ReceiptReprintLogs','SalesReturns','OrderSequences','InvoiceSequences']
    LOOP
        column_name := CASE WHEN history_table IN ('OrderSequences','InvoiceSequences') THEN 'terminal_id' ELSE 'TerminalId' END;
        EXECUTE format('SELECT count(*) FROM %I h LEFT JOIN "Terminals" t ON t."TerminalId" = h.%I WHERE t."TerminalId" IS NULL', history_table, column_name) INTO invalid_count;
        IF invalid_count > 0 THEN
            RAISE EXCEPTION 'Orphaned machine references in %. Resolve them before migration; history is not discarded.', history_table;
        END IF;
        IF EXISTS (SELECT 1 FROM information_schema.columns c WHERE c.table_schema=current_schema() AND c.table_name=history_table AND c.column_name='BranchId') THEN
            EXECUTE format('SELECT count(*) FROM %I h JOIN "Terminals" t ON t."TerminalId"=h.%I WHERE h."BranchId"<>t."BranchId"', history_table, column_name) INTO invalid_count;
            IF invalid_count > 0 THEN RAISE EXCEPTION 'Historical branch/terminal mismatch in %. Review ownership before migration.', history_table; END IF;
        END IF;
    END LOOP;
END $validate$;

