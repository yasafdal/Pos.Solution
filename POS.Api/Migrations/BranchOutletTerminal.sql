-- Historical terminal references are protected from deletion at the database boundary as well as in CRUD.
DO $foreign_keys$
DECLARE history_table text; history_column text; constraint_name text; item record;
BEGIN
    FOR item IN SELECT conname FROM pg_constraint WHERE conrelid = '"Terminals"'::regclass AND confrelid = '"Branches"'::regclass
    LOOP
        EXECUTE format('ALTER TABLE "Terminals" DROP CONSTRAINT %I', item.conname);
    END LOOP;
    ALTER TABLE "Terminals" ADD CONSTRAINT "Terminals_BranchId_fkey" FOREIGN KEY ("BranchId") REFERENCES "Branches"("BranchId") ON DELETE RESTRICT;
    FOREACH history_table IN ARRAY ARRAY['Orders','CashDrawerShifts','CashDrawerMovements','CashierSessions','CashierSwitchLogs','HeldSales','HeldSaleAuditLogs','ReceiptReprintLogs','SalesReturns','OrderSequences','InvoiceSequences']
    LOOP
        history_column := CASE WHEN history_table IN ('OrderSequences','InvoiceSequences') THEN 'terminal_id' ELSE 'TerminalId' END;
        FOR item IN SELECT conname FROM pg_constraint WHERE conrelid = to_regclass(format('%I', history_table)) AND confrelid = '"Terminals"'::regclass
        LOOP
            EXECUTE format('ALTER TABLE %I DROP CONSTRAINT %I', history_table, item.conname);
        END LOOP;
        constraint_name := CASE WHEN history_table IN ('OrderSequences','InvoiceSequences') THEN 'FK_' || history_table || '_Terminal' ELSE 'FK_' || history_table || '_Terminals_TerminalId' END;
        EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I FOREIGN KEY (%I) REFERENCES "Terminals"("TerminalId") ON DELETE RESTRICT', history_table, constraint_name, history_column);
        EXECUTE format('CREATE INDEX IF NOT EXISTS %I ON %I (%I)', 'IX_' || history_table || '_TerminalId', history_table, history_column);
    END LOOP;
END $foreign_keys$;

